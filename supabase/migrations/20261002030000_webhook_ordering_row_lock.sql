--
-- PROBLEM
-- 20261002000000_webhook_ordering_guard.sql reads
-- last_applied_occurred_at with a plain SELECT, then updates the
-- subscription. Two distinct events for the same subscription can both
-- read the old marker and then update in either order, so an older event
-- can commit after (and overwrite) a newer event.
--
-- FIX
-- Lock the target subscription row with SELECT ... FOR UPDATE before the
-- ordering comparison. The second delivery blocks until the first commits
-- and, under READ COMMITTED, re-reads the committed marker (EvalPlanQual),
-- so it can classify itself as stale against the value that actually won.
-- The event claim remains before the lock: duplicate deliveries never need
-- a row lock and still return inserted=false with no mutation.
--
-- ROLLBACK STANCE: forward-fix only. To revert, deploy a new migration;
-- do not edit this file after it has been applied.

CREATE OR REPLACE FUNCTION public.apply_paystack_event(
    p_provider                 TEXT,
    p_provider_event_id        TEXT,
    p_event_type               TEXT,
    p_payload                  JSONB,
    p_processing_status        TEXT,
    p_error_code               TEXT,
    p_subscription_id          BIGINT,
    p_apply_subscription       BOOLEAN,
    p_new_status               TEXT,
    p_provider_customer_id     TEXT,
    p_provider_subscription_id TEXT,
    p_current_period_start     TIMESTAMPTZ,
    p_current_period_end       TIMESTAMPTZ,
    p_provider_occurred_at     TIMESTAMPTZ DEFAULT NULL,
    p_provider_sequence        TEXT DEFAULT NULL
)
RETURNS TABLE (event_id BIGINT, inserted BOOLEAN)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_event_id BIGINT;
    v_last_applied TIMESTAMPTZ;
BEGIN
    INSERT INTO public.subscription_events (
        subscription_id, provider, provider_event_id, event_type, payload,
        processing_status, error_code, provider_occurred_at,
        provider_sequence
    )
    VALUES (
        p_subscription_id, p_provider, p_provider_event_id, p_event_type,
        COALESCE(p_payload, '{}'::jsonb), p_processing_status, p_error_code,
        p_provider_occurred_at, p_provider_sequence
    )
    ON CONFLICT (provider, provider_event_id) DO NOTHING
    RETURNING id INTO v_event_id;

    IF v_event_id IS NULL THEN
        -- Already recorded: a duplicate delivery. No mutation of anything.
        RETURN QUERY SELECT NULL::BIGINT, false;
        RETURN;
    END IF;

    IF COALESCE(p_apply_subscription, false)
       AND p_subscription_id IS NOT NULL
       AND p_new_status IS NOT NULL THEN
        -- Serialize all ordering decisions for this subscription. The
        -- provider predicate keeps the lock (and the later UPDATE) scoped
        -- to the row this provider is allowed to mutate. Under READ
        -- COMMITTED, a waiter re-reads the row version committed by the
        -- first writer, so the marker below is the winning value.
        SELECT s.last_applied_occurred_at INTO v_last_applied
          FROM public.subscriptions AS s
         WHERE s.id = p_subscription_id
           AND s.provider = p_provider
         FOR UPDATE;

        -- Stale-event guard (NULL-tolerant): skip the subscription update
        -- only when BOTH the stored marker and the incoming timestamp are
        -- known AND the incoming event is strictly older. In every other
        -- case (either side NULL, equal, or newer) apply normally.
        IF v_last_applied IS NULL
           OR p_provider_occurred_at IS NULL
           OR p_provider_occurred_at >= v_last_applied THEN
            UPDATE public.subscriptions AS s
               SET status                   = p_new_status,
                   provider                 = COALESCE(p_provider, s.provider),
                   provider_customer_id     = COALESCE(p_provider_customer_id, s.provider_customer_id),
                   provider_subscription_id = COALESCE(p_provider_subscription_id, s.provider_subscription_id),
                   current_period_start     = COALESCE(p_current_period_start, s.current_period_start),
                   current_period_end       = COALESCE(p_current_period_end, s.current_period_end),
                   last_applied_occurred_at = GREATEST(
                       COALESCE(s.last_applied_occurred_at, p_provider_occurred_at),
                       p_provider_occurred_at)
             WHERE s.id = p_subscription_id
               AND s.provider = p_provider;
        ELSE
            -- Provably stale: leave the subscription untouched and mark
            -- the recorded event so the audit trail shows why nothing
            -- changed.
            UPDATE public.subscription_events
               SET processing_status = 'ignored',
                   error_code = 'stale_event'
             WHERE id = v_event_id;
            IF p_processing_status IN ('processed', 'ignored', 'failed') THEN
                UPDATE public.subscription_events
                   SET processed_at = now()
                 WHERE id = v_event_id;
            END IF;
            RETURN QUERY SELECT v_event_id, true;
            RETURN;
        END IF;
    END IF;

    IF p_processing_status IN ('processed', 'ignored', 'failed') THEN
        UPDATE public.subscription_events
           SET processed_at = now()
         WHERE id = v_event_id;
    END IF;

    RETURN QUERY SELECT v_event_id, true;
END;
$$;

REVOKE ALL ON FUNCTION public.apply_paystack_event(
    TEXT, TEXT, TEXT, JSONB, TEXT, TEXT, BIGINT, BOOLEAN, TEXT, TEXT, TEXT,
    TIMESTAMPTZ, TIMESTAMPTZ, TIMESTAMPTZ, TEXT
) FROM PUBLIC, anon, authenticated;

