-- ---------- 1. whatsapp_accounts ----------
CREATE TABLE IF NOT EXISTS public.whatsapp_accounts (
    id               BIGSERIAL PRIMARY KEY,
    user_id          UUID                     NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    whatsapp_user_id TEXT                     NOT NULL,
    display_name     TEXT                     NULL,
    status           TEXT                     NOT NULL DEFAULT 'linked',
    linked_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at     TIMESTAMPTZ NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT whatsapp_accounts_user_id_key UNIQUE (user_id),
    CONSTRAINT whatsapp_accounts_whatsapp_user_id_key UNIQUE (whatsapp_user_id),
    CONSTRAINT whatsapp_accounts_status_check CHECK (status IN ('linked', 'unlinked'))
);

ALTER TABLE public.whatsapp_accounts ENABLE ROW LEVEL SECURITY;

-- Deny by default: strip default-privilege grants and grant nothing to
-- anon/authenticated. service_role keeps its default full rights for
-- trusted server-side adapter processing (table-owner path bypasses
-- RLS; no policy is needed for it, none is created for anyone else).
REVOKE ALL ON TABLE public.whatsapp_accounts FROM anon, authenticated;

