-- ---------- 5. whatsapp_deliveries (notification outbox) ----------
-- One row per (category, entity, user). UNIQUE(idempotency_key) is the
-- duplicate arbiter: concurrent collectors/inserts for the same
-- notification collapse to a single row. Lifecycle: pending ->
-- sending -> sent | failed, with bounded attempts and claim leases
-- (claimed_until). Abandoned sending rows (lease expired) become
-- claimable again; ambiguous provider timeouts return the row to
-- pending with attempts incremented and last_error set, explicitly
-- NOT counted as sent (at-least-once, never claimed exactly-once).
CREATE TABLE IF NOT EXISTS public.whatsapp_deliveries (
    id                 BIGSERIAL PRIMARY KEY,
    idempotency_key    TEXT        NOT NULL,
    user_id            UUID        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    category           TEXT        NOT NULL,
    entity_type        TEXT        NULL,
    entity_id          TEXT        NULL,
    payload_hash       TEXT        NULL,
    body               TEXT        NULL,
    status             TEXT        NOT NULL DEFAULT 'pending',
    attempts           INTEGER     NOT NULL DEFAULT 0,
    max_attempts       INTEGER     NOT NULL DEFAULT 3,
    claimed_until      TIMESTAMPTZ NULL,
    provider_message_id TEXT       NULL,
    provider_status    TEXT        NULL,
    last_error         TEXT        NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at            TIMESTAMPTZ NULL,

    CONSTRAINT whatsapp_deliveries_key_key UNIQUE (idempotency_key),
    CONSTRAINT whatsapp_deliveries_category_check CHECK (category IN ('match_update', 'prediction_alert')),
    CONSTRAINT whatsapp_deliveries_status_check CHECK (status IN ('pending', 'sending', 'sent', 'failed'))
);

ALTER TABLE public.whatsapp_deliveries ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.whatsapp_deliveries FROM anon, authenticated;

CREATE INDEX IF NOT EXISTS whatsapp_deliveries_claim_idx
    ON public.whatsapp_deliveries (status, claimed_until, attempts);

CREATE INDEX IF NOT EXISTS whatsapp_deliveries_user_idx
    ON public.whatsapp_deliveries (user_id);

-- ---------- 6. atomic outbox claim (production concurrency boundary) ----------
-- Single-call claim for whatsapp_deliveries: SELECT ... FOR UPDATE SKIP
-- LOCKED + conditional UPDATE in one function invocation, so two
-- concurrent workers can never receive the same delivery. Narrowly scoped
-- to whatsapp_deliveries only: claims one eligible row (pending, or
-- sending with an expired lease), subject to attempts < max_attempts.
-- Sets status='sending', claimed_until=p_lease_until, attempts+1, and
-- returns the complete claimed row (0 rows when no eligible delivery).
-- Never claims sent/failed rows or exhausted (attempts >= max_attempts)
-- rows. Ambiguous provider timeouts are NOT resolved here: the caller
-- returns the row to pending with attempts incremented and last_error
-- set (at-least-once, never claimed exactly-once). Idempotency still
-- rests on UNIQUE(idempotency_key) at insert time; this function only
-- arbitrates the pending->sending claim.
CREATE OR REPLACE FUNCTION public.claim_whatsapp_delivery(
    p_now TIMESTAMPTZ,
    p_lease_until TIMESTAMPTZ
)
RETURNS SETOF public.whatsapp_deliveries
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_id BIGINT;
BEGIN
    SELECT d.id INTO v_id
    FROM public.whatsapp_deliveries AS d
    WHERE d.attempts < d.max_attempts
      AND (
            d.status = 'pending'
         OR (d.status = 'sending'
             AND (d.claimed_until IS NULL OR d.claimed_until <= p_now))
          )
    ORDER BY d.id
    FOR UPDATE SKIP LOCKED
    LIMIT 1;

    IF v_id IS NULL THEN
        RETURN;
    END IF;

    RETURN QUERY
    UPDATE public.whatsapp_deliveries AS d
    SET status = 'sending',
        claimed_until = p_lease_until,
        attempts = d.attempts + 1
    WHERE d.id = v_id
      AND d.attempts < d.max_attempts
      AND (
            d.status = 'pending'
         OR (d.status = 'sending'
             AND (d.claimed_until IS NULL OR d.claimed_until <= p_now))
          )
    RETURNING d.*;
END;
$$;

-- Service-role only: the claim function runs server-side. No anon/
-- authenticated access (deny by default, matching the tables above).
REVOKE ALL ON FUNCTION public.claim_whatsapp_delivery(TIMESTAMPTZ, TIMESTAMPTZ) FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_whatsapp_delivery(TIMESTAMPTZ, TIMESTAMPTZ) TO service_role;

-- ---------- 7. updated_at maintenance (narrowly scoped) ----------
CREATE OR REPLACE FUNCTION public.handle_whatsapp_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_whatsapp_accounts_updated_at ON public.whatsapp_accounts;
CREATE TRIGGER trg_whatsapp_accounts_updated_at
    BEFORE UPDATE ON public.whatsapp_accounts
    FOR EACH ROW EXECUTE FUNCTION public.handle_whatsapp_updated_at();

DROP TRIGGER IF EXISTS trg_whatsapp_preferences_updated_at ON public.whatsapp_preferences;
CREATE TRIGGER trg_whatsapp_preferences_updated_at
    BEFORE UPDATE ON public.whatsapp_preferences
    FOR EACH ROW EXECUTE FUNCTION public.handle_whatsapp_updated_at();

DROP TRIGGER IF EXISTS trg_whatsapp_deliveries_updated_at ON public.whatsapp_deliveries;
CREATE TRIGGER trg_whatsapp_deliveries_updated_at
    BEFORE UPDATE ON public.whatsapp_deliveries
    FOR EACH ROW EXECUTE FUNCTION public.handle_whatsapp_updated_at();

